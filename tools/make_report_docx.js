function IMG(file, w, h, maxW = 560) {
  const p = FIG(file); if (!fs.existsSync(p)) return BLANK('(그림 없음: ' + file + ')');
  const s = Math.min(1, maxW / w, 760 / h);
  return new Paragraph({ children: [new ImageRun({ type: 'png', data: fs.readFileSync(p), transformation: { width: Math.round(w * s), height: Math.round(h * s) } })], alignment: AlignmentType.CENTER, spacing: { before: 120, after: 60 } });
}
